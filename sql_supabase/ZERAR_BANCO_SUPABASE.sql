-- ------------------------------------------------------------------------------------
-- ETAPA 2: CRIAÇÃO DE TODAS AS TABELAS LIMPAS E ATUALIZADAS
-- ------------------------------------------------------------------------------------

-- 1. TABELA DE USUÁRIOS
CREATE TABLE public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    phone VARCHAR(30) DEFAULT NULL,
    saldo NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    role VARCHAR(20) NOT NULL DEFAULT 'client',
    status VARCHAR(20) NOT NULL DEFAULT 'approved',
    plano VARCHAR(50) DEFAULT 'Nenhum',
    plano_status VARCHAR(20) DEFAULT 'inativo',
    plano_desconto INT DEFAULT 0,
    plano_comissao INT DEFAULT 0,
    plano_validade VARCHAR(50) DEFAULT 'Vitalício',
    plano_ativado_em TIMESTAMPTZ DEFAULT NULL,
    register_ip VARCHAR(64) DEFAULT NULL,
    last_ip VARCHAR(64) DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 2. TABELA DE CONFIGURAÇÕES GERAIS DO SISTEMA
CREATE TABLE public.configuracoes (
    chave VARCHAR(100) PRIMARY KEY,
    valor TEXT
);

-- 3. TABELA DE ATESTADOS MÉDICOS
CREATE TABLE public.atestados (
    id VARCHAR(50) PRIMARY KEY,
    user_id BIGINT,
    user_nome VARCHAR(150),
    paciente_nome VARCHAR(150),
    cpf VARCHAR(30),
    cns VARCHAR(30),
    medico_nome VARCHAR(150),
    crm VARCHAR(50),
    cid VARCHAR(50),
    dias_repouso INT,
    unidade_saude VARCHAR(255),
    valor_cobrado NUMERIC(10,2) DEFAULT 10.00,
    dados_json TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 4. TABELA DE CNHS GERADAS
CREATE TABLE public.cnhs (
    id VARCHAR(50) PRIMARY KEY,
    user_id BIGINT,
    user_nome VARCHAR(150),
    nome_cnh VARCHAR(150),
    cpf VARCHAR(30),
    rg VARCHAR(50),
    categoria VARCHAR(20) DEFAULT 'B',
    genero VARCHAR(20) DEFAULT 'Feminino',
    valor_cobrado NUMERIC(10,2) DEFAULT 25.00,
    valor_pendencia VARCHAR(50) DEFAULT '500,00',
    dados_json TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 5. TABELA DE EXAMES TOXICOLÓGICOS
CREATE TABLE public.exames (
    id VARCHAR(50) PRIMARY KEY,
    user_id BIGINT,
    user_nome VARCHAR(150),
    paciente_nome VARCHAR(150),
    cpf VARCHAR(30),
    resultado VARCHAR(20) DEFAULT 'Negativo',
    laboratorio VARCHAR(150),
    data_coleta DATE,
    data_laudo DATE,
    valor_cobrado NUMERIC(10,2) DEFAULT 20.00,
    dados_json TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 6. TABELA DE RECARGAS & COMPROVANTES PIX
CREATE TABLE public.recargas (
    id VARCHAR(50) PRIMARY KEY,
    user_id BIGINT,
    user_nome VARCHAR(150),
    valor NUMERIC(10,2) NOT NULL,
    metodo VARCHAR(50) DEFAULT 'PIX QrCode',
    status VARCHAR(20) DEFAULT 'pending',
    comprovante TEXT,
    data TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 7. TABELA DE INDICAÇÕES E AFILIADOS
CREATE TABLE public.indicacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicador_id BIGINT,
    indicador_nome VARCHAR(150),
    indicador_email VARCHAR(150),
    indicado_id BIGINT,
    indicado_nome VARCHAR(150),
    indicado_email VARCHAR(150),
    bonus_recebido NUMERIC(10,2) DEFAULT 0.00,
    status VARCHAR(20) DEFAULT 'pendente',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 8. TABELA DE LOGS DE ATIVIDADES
CREATE TABLE public.atividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    user_nome VARCHAR(150),
    tipo VARCHAR(50),
    descricao TEXT,
    sub_rotulo VARCHAR(150),
    valor NUMERIC(10,2) DEFAULT 0.00,
    tag_class VARCHAR(50),
    tag_text VARCHAR(50),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 9. TABELA DE ASSINANTES E PLANOS REVENDEDOR
CREATE TABLE public.assinantes (
    id BIGSERIAL PRIMARY KEY,
    user_id TEXT NOT NULL UNIQUE,
    user_nome VARCHAR(150),
    user_email VARCHAR(150),
    user_phone VARCHAR(50),
    plano VARCHAR(50) NOT NULL,
    valor NUMERIC(10, 2) DEFAULT 0.00,
    desconto_doc INT DEFAULT 0,
    comissao_indicacao INT DEFAULT 0,
    status VARCHAR(20) DEFAULT 'ativo',
    validade VARCHAR(50) DEFAULT 'Vitalício',
    observacao TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);


